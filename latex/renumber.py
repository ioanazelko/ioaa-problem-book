#!/usr/bin/env python
"""Renumber every \\probhead and \\solhead in the chapter files in file order.

Problem numbers run continuously through a chapter in order of appearance;
the i-th \\solhead gets the number of the i-th \\probhead. The script checks
that each chapter has as many solutions as problems and that the titles agree
pairwise, and prints every number that changed. Nothing else depends on the
numbers: the cross-links are generated by the macros, and errata.tex is
regenerated by build_errata.py.

Usage: python renumber.py [chNN ...]      (default: all chapters)
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CH = os.path.join(HERE, "chapters")


def brace_args(line, n):
    """Return the first n brace-delimited arguments after the macro name."""
    i = line.index("{")
    out = []
    for _ in range(n):
        assert line[i] == "{", line
        depth, j = 0, i
        while True:
            if line[j] == "{":
                depth += 1
            elif line[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append(line[i + 1:j])
        i = j + 1
    return out


def renumber(path):
    chap = int(re.search(r"ch(\d+)\.tex$", path).group(1))
    lines = open(path).read().split("\n")
    probs = [i for i, l in enumerate(lines) if l.startswith("\\probhead{")]
    sols = [i for i, l in enumerate(lines) if l.startswith("\\solhead{")]
    if len(probs) != len(sols):
        raise SystemExit(f"{path}: {len(probs)} problems but {len(sols)} solutions")
    changed = 0
    for k, (pi, si) in enumerate(zip(probs, sols), 1):
        pnum, ptitle = brace_args(lines[pi], 2)
        snum, stitle = brace_args(lines[si], 2)
        if ptitle != stitle:
            raise SystemExit(f"{path}: title mismatch at problem {k}: {ptitle!r} vs {stitle!r}")
        num = f"{chap}.{k}"
        for idx, old, macro in ((pi, pnum, "probhead"), (si, snum, "solhead")):
            if old != num:
                lines[idx] = f"\\{macro}{{{num}}}" + lines[idx][len(f"\\{macro}{{{old}}}"):]
                changed += 1
                print(f"  {macro} {old} -> {num}")
    open(path, "w").write("\n".join(lines))
    print(f"{os.path.basename(path)}: {len(probs)} problems, {changed} numbers changed")


if __name__ == "__main__":
    names = sys.argv[1:] or sorted(f[:-4] for f in os.listdir(CH) if re.match(r"ch\d+\.tex$", f))
    for n in names:
        renumber(os.path.join(CH, n + ".tex"))
